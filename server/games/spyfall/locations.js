  function allLocations(packIds) {
    var ids = packIds && packIds.length ? packIds : PACKS.map(function (p) { return p.id; });
    var out = [];
    PACKS.forEach(function (p) {
      if (ids.indexOf(p.id) < 0) return;
      p.locations.forEach(function (loc) { out.push(loc); });
    });
    return out;
  }

  function pickLocation(packIds) {
    var list = allLocations(packIds);
    if (!list.length) return null;
    return list[Math.floor(Math.random() * list.length)];
  }

  /** รายชื่อสถานที่ทั้งหมดที่สายลับใช้เดา — ต้องเรียงเหมือนกันทุกคนจะได้คุยกันรู้เรื่อง */
  function locationNames(packIds) {
    return allLocations(packIds).map(function (l) { return l.name; }).sort();
  }

