  function packById(id) {
    for (var i = 0; i < PACKS.length; i++) if (PACKS[i].id === id) return PACKS[i];
    return null;
  }

  /**
   * @param {string} packId
   * @param {string} level "common" | "rare" | "both"
   */
  function pickWord(packId, level) {
    var pack = packById(packId);
    if (!pack) return null;

    var pool = level === "rare" ? pack.rare
      : level === "common" ? pack.common
      : pack.common.concat(pack.rare);

    if (!pool.length) return null;
    return pool[Math.floor(Math.random() * pool.length)];
  }

  function hintsFor(packId) {
    var pack = packById(packId);
    var group = pack ? pack.group : "สิ่งของ";
    return HINTS[group] || HINTS["สิ่งของ"];
  }

  function randomHint(packId, exclude) {
    var list = hintsFor(packId).filter(function (h) {
      return !exclude || exclude.indexOf(h) < 0;
    });
    if (!list.length) list = hintsFor(packId);
    return list[Math.floor(Math.random() * list.length)];
  }

